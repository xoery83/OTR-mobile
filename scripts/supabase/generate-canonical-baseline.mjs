import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const auditDir = process.env.OTR_SCHEMA_AUDIT_DIR;

if (!auditDir) {
  throw new Error("Set OTR_SCHEMA_AUDIT_DIR to the read-only metadata export directory.");
}

const outputPath = path.resolve(
  "supabase/migrations/20260910000100_canonical_production_baseline.sql",
);

async function loadExport(name) {
  const outer = JSON.parse(await readFile(path.join(auditDir, `${name}.json`), "utf8"));
  const row = outer[0];
  const value = row[Object.keys(row)[0]];
  return typeof value === "string" ? JSON.parse(value) : value;
}

function identifier(value) {
  return `"${value.replaceAll('"', '""')}"`;
}

function literal(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function terminate(statement) {
  return `${statement.trim().replace(/;+$/, "")};`;
}

const [
  columns,
  constraints,
  indexes,
  functions,
  triggers,
  rlsAndPolicies,
  buckets,
  enums,
] = await Promise.all([
  loadExport("canonical-columns"),
  loadExport("constraints"),
  loadExport("indexes"),
  loadExport("functions"),
  loadExport("triggers"),
  loadExport("rls-policies"),
  loadExport("storage-buckets"),
  loadExport("enum-labels"),
]);

const tables = Map.groupBy(columns, (column) => column.table);

if (tables.size !== 64 || columns.length !== 910) {
  throw new Error(
    `Refusing to generate: expected 64 tables / 910 columns, received ${tables.size} / ${columns.length}.`,
  );
}

const lines = [
  "-- OTR canonical production-shape baseline.",
  "-- Generated from the read-only production metadata audit dated 2026-09-10.",
  "-- Contains schema and synthetic-free bucket declarations only; no production rows.",
  "-- Do not apply this baseline to the legacy production project.",
  "",
  "create extension if not exists pgcrypto with schema extensions;",
  "",
];

for (const item of enums) {
  lines.push(
    `create type ${identifier(item.schema)}.${identifier(item.name)} as enum (${item.labels
      .map(literal)
      .join(", ")});`,
    "",
  );
}

for (const [tableName, tableColumns] of [...tables.entries()].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const definitions = tableColumns.map((column) => {
    const parts = [identifier(column.name), column.type];
    if (column.collation) parts.push(`collate ${identifier(column.collation)}`);
    if (column.generated === "s")
      parts.push(`generated always as (${column.default}) stored`);
    else if (column.identity === "a") parts.push("generated always as identity");
    else if (column.identity === "d") parts.push("generated by default as identity");
    else if (column.default !== null) parts.push(`default ${column.default}`);
    if (column.not_null) parts.push("not null");
    return `  ${parts.join(" ")}`;
  });

  lines.push(
    `create table public.${identifier(tableName)} (`,
    definitions.join(",\n"),
    ");",
    "",
  );
}

const nonForeignConstraints = constraints.filter((constraint) => constraint.type !== "f");
const foreignConstraints = constraints.filter((constraint) => constraint.type === "f");

for (const constraint of [...nonForeignConstraints, ...foreignConstraints]) {
  lines.push(
    `alter table public.${identifier(constraint.table)} add constraint ${identifier(
      constraint.name,
    )} ${constraint.definition};`,
  );
}
lines.push("");

const constraintIndexNames = new Set(
  constraints
    .filter((constraint) => constraint.type === "p" || constraint.type === "u")
    .map((constraint) => constraint.name),
);

for (const index of indexes.filter((item) => !constraintIndexNames.has(item.name))) {
  lines.push(terminate(index.definition));
}
lines.push("");

const functionOrder = [
  "touch_updated_at",
  "touch_journey_chat_message_updated_at",
  "is_trip_member",
  "is_trip_creator",
  "is_trip_member_or_creator",
  "is_trip_owner_or_admin",
  "is_system_admin",
  "can_access_trip_media",
  "can_upload_trip_media",
  "can_access_memory_shot_preview",
  "can_manage_background_jobs",
  "can_manage_itinerary_event_participants",
  "can_manage_itinerary_reservation_participants",
  "add_trip_creator_as_member",
  "add_trip_creator_as_journey_member",
];

const functionRank = new Map(functionOrder.map((name, index) => [name, index]));
for (const fn of [...functions].sort((a, b) => {
  const left = functionRank.get(a.name) ?? 1000;
  const right = functionRank.get(b.name) ?? 1000;
  return left - right || a.name.localeCompare(b.name);
})) {
  lines.push(terminate(fn.definition), "");
}

for (const trigger of triggers) {
  lines.push(terminate(trigger.definition));
}
lines.push("");

for (const table of rlsAndPolicies.rls.filter((item) => item.schema === "public")) {
  lines.push(`alter table public.${identifier(table.table)} enable row level security;`);
}
lines.push("");

for (const policy of rlsAndPolicies.policies) {
  const clauses = [
    `create policy ${identifier(policy.name)}`,
    `  on ${identifier(policy.schema)}.${identifier(policy.table)}`,
    `  for ${policy.command.toLowerCase()}`,
    `  to ${policy.roles.map(identifier).join(", ")}`,
  ];
  if (policy.using) clauses.push(`  using (${policy.using})`);
  if (policy.check) clauses.push(`  with check (${policy.check})`);
  lines.push(`${clauses.join("\n")};`, "");
}

for (const bucket of buckets) {
  const mimeTypes = bucket.allowed_mime_types
    ? `array[${bucket.allowed_mime_types.map(literal).join(", ")}]::text[]`
    : "null";
  lines.push(
    "insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)",
    `values (${literal(bucket.id)}, ${literal(bucket.name)}, ${bucket.public}, ${
      bucket.file_size_limit ?? "null"
    }, ${mimeTypes})`,
    "on conflict (id) do nothing;",
    "",
  );
}

lines.push(
  "grant usage on schema public to anon, authenticated, service_role;",
  "grant all on all tables in schema public to anon, authenticated, service_role;",
  "grant all on all sequences in schema public to anon, authenticated, service_role;",
  "",
);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${lines.join("\n").trim()}\n`, "utf8");
console.log(
  `Generated ${outputPath} (${tables.size} tables / ${columns.length} columns).`,
);
