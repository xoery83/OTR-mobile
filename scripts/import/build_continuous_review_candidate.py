    guard = once(guard, ' continuous_candidate jsonb; continuous_expiry jsonb;', ' accepted_recovery boolean:=false; accepted_receipt public.trip_core_command_receipts;\n continuous_candidate jsonb; continuous_expiry jsonb;')
    recovery = (PACKET / 'ACCEPTED_RECOVERY_SCOPE.sql').read_text()
    marker = "  RETURN;\n END IF;\n IF session_user<>"
    guard = once(guard, marker, "  RETURN;\n END IF;\n" + recovery + " IF session_user<>")
    old = " OR NOT EXISTS(SELECT 1 FROM public.trip_sustained_import_p1_capabilities(actor,trip) c WHERE c.runtime_enabled)\n OR current_setting('otr.core.admission',true)"
    guard = once(guard, old, " OR (NOT accepted_recovery AND NOT EXISTS(SELECT 1 FROM public.trip_sustained_import_p1_capabilities(actor,trip) c WHERE c.runtime_enabled))\n OR current_setting('otr.core.admission',true)")
    guard = once(guard, " IF review_scope->>'mode'='CONTINUOUS_MINIMUMS' THEN", " IF review_scope->>'mode'='CONTINUOUS_MINIMUMS' OR accepted_recovery THEN")
    guard = once(guard, "  continuous_expiry:=review_scope->'expiresAt';", "  continuous_expiry:=coalesce(review_scope->'expiresAt',to_jsonb('1970-01-01T00:00:00Z'::text));")
    old_expiry = " OR NOT coalesce((review_scope->>'expiresAt')::timestamptz>clock_timestamp(),false)\n THEN RAISE EXCEPTION 'P1_SOURCE_REVIEW_SCOPE_CLOSED'"
    guard = once(guard,old_expiry," OR (NOT accepted_recovery AND NOT coalesce((review_scope->>'expiresAt')::timestamptz>clock_timestamp(),false))\n THEN RAISE EXCEPTION 'P1_SOURCE_REVIEW_SCOPE_CLOSED'")
